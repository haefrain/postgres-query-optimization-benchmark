/** Renders a JS string array as a Postgres text[] literal, escaping quotes. */
export function sqlTextArray(values: string[]): string {
  const escaped = values.map((v) => `'${v.replace(/'/g, "''")}'`).join(', ');
  return `ARRAY[${escaped}]::text[]`;
}
